INSERT INTO Дисциплины (Название, Описание, Год_введения)
SELECT 'Основы электротехники', 'Базовые понятия электротехники', 2016
WHERE NOT EXISTS (SELECT 1 FROM Дисциплины WHERE Название = 'Основы электротехники');


-- =========================================================
-- Запрос 1 (выборка). Все дисциплины, стандарт на которые
-- был введен более 5 лет назад.
-- =========================================================
SELECT *
FROM Дисциплины
WHERE Год_введения < EXTRACT(YEAR FROM CURRENT_DATE) - 5;


-- =========================================================
-- Запрос 2 (выборка). Дисциплины, которые читают
-- преподаватели с почасовой оплатой.
-- =========================================================
SELECT DISTINCT д.*
FROM Дисциплины д
JOIN Нагрузка н ON д.Код_дисциплины = н.Код_дисциплины
WHERE н.Почасовая_оплата > 0;


-- =========================================================
-- Запрос 3 (создание таблицы). Таблица с данными запроса 2:
-- код, название, описание и год введения дисциплин.
-- DROP позволяет запускать скрипт повторно.
-- =========================================================
DROP TABLE IF EXISTS Почасовые_дисциплины;

CREATE TABLE Почасовые_дисциплины AS
SELECT DISTINCT д.Код_дисциплины,
       д.Название,
       д.Описание,
       д.Год_введения
FROM Дисциплины д
JOIN Нагрузка н ON д.Код_дисциплины = н.Код_дисциплины
WHERE н.Почасовая_оплата > 0;

SELECT * FROM Почасовые_дисциплины ORDER BY Код_дисциплины;


-- =========================================================
-- Запрос 4 (Insert Select). Добавить дисциплины, название
-- которых состоит из нескольких слов и начинается
-- со слова «основы». NOT EXISTS исключает дубли по коду.
-- =========================================================
INSERT INTO Почасовые_дисциплины
    (Код_дисциплины, Название, Описание, Год_введения)
SELECT д.Код_дисциплины,
       д.Название,
       д.Описание,
       д.Год_введения
FROM Дисциплины д
WHERE д.Название ILIKE 'основы %'
  AND NOT EXISTS (
      SELECT 1
      FROM Почасовые_дисциплины п
      WHERE п.Код_дисциплины = д.Код_дисциплины
  );

SELECT * FROM Почасовые_дисциплины ORDER BY Код_дисциплины;


-- =========================================================
-- Запрос 5 (Update). Изменить год введения на 2009
-- всем дисциплинам с четным кодом.
-- =========================================================
UPDATE Почасовые_дисциплины
SET Год_введения = 2009
WHERE Код_дисциплины % 2 = 0;

SELECT * FROM Почасовые_дисциплины ORDER BY Код_дисциплины;


-- =========================================================
-- Запрос 6 (Delete). Удалить записи для всех дисциплин,
-- в названии которых встречается слово «математика».
-- =========================================================
DELETE FROM Почасовые_дисциплины
WHERE Название ILIKE '%математика%';

SELECT * FROM Почасовые_дисциплины ORDER BY Код_дисциплины;


-- =========================================================
-- Запрос 7 (групповой). Количество вводимых дисциплин
-- за каждые 5 лет, начиная с 1990 года.
-- =========================================================
SELECT
    1990 + ((Год_введения - 1990) / 5) * 5 AS Начало_периода,
    COUNT(*) AS Количество_дисциплин
FROM Дисциплины
WHERE Год_введения >= 1990
GROUP BY Начало_периода
ORDER BY Начало_периода;


