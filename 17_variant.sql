-- =========================================================
-- Задание 1. Выбрать все дисциплины, стандарт на которые
-- был введен более 5 лет назад.
-- Встроенные функции: EXTRACT — извлекает год из даты;
-- CURRENT_DATE — возвращает текущую дату.
-- =========================================================
SELECT *
FROM Дисциплины
WHERE Год_введения < EXTRACT(YEAR FROM CURRENT_DATE) - 5;


-- =========================================================
-- Задание 2. Выбрать дисциплины, которые читают
-- преподаватели с почасовой оплатой.
-- JOIN объединяет таблицы по коду дисциплины.
-- =========================================================
SELECT д.*
FROM Дисциплины д
JOIN Нагрузка н ON д.Код = н.Код_дисциплины
WHERE н.Оплата_часа > 0;


-- =========================================================
-- Задание 3. Создать таблицу, содержащую данные 2 запроса
-- с указанием описания и года введения дисциплин
-- согласно стандарту.
-- DROP TABLE удаляет ранее созданную таблицу, если она есть,
-- чтобы скрипт можно было запускать повторно с начала.
-- =========================================================
DROP TABLE IF EXISTS Почасовые_дисциплины;

CREATE TABLE Почасовые_дисциплины AS
SELECT д.Код,
       д.Название,
       д.Описание,
       д.Год_введения
FROM Дисциплины д
JOIN Нагрузка н ON д.Код = н.Код_дисциплины
WHERE н.Оплата_часа > 0;


-- =========================================================
-- Задание 4. Добавить дисциплины, название которых состоит
-- из нескольких слов и начинается со слова «основы».
-- Инструкция Insert Select; NOT EXISTS не позволяет добавить
-- повторно уже имеющийся код.
-- =========================================================
INSERT INTO Почасовые_дисциплины
    (Код, Название, Описание, Год_введения)
SELECT д.Код,
       д.Название,
       д.Описание,
       д.Год_введения
FROM Дисциплины д
WHERE д.Название ILIKE 'основы %'
  AND NOT EXISTS (
      SELECT 1
      FROM Почасовые_дисциплины п
      WHERE п.Код = д.Код
  );


-- =========================================================
-- Задание 5. В созданной таблице изменить год введения
-- на 2009 всем дисциплинам с четным кодом.
-- Инструкция Update; % — остаток от деления, 0 означает
-- четный код.
-- =========================================================
UPDATE Почасовые_дисциплины
SET Год_введения = 2009
WHERE Код % 2 = 0;


-- =========================================================
-- Задание 6. Удалить из созданной таблицы записи для всех
-- дисциплин, в названии которых встречается слово «математика».
-- Инструкция Delete; ILIKE — поиск без учета регистра.
-- =========================================================
DELETE FROM Почасовые_дисциплины
WHERE Название ILIKE '%математика%';


-- =========================================================
-- Задание 7. Посчитать количество вводимых дисциплин
-- за каждые 5 лет, начиная с 1990 года.
-- Групповой запрос с агрегативной функцией COUNT.
-- =========================================================
SELECT
    1990 + ((Год_введения - 1990) / 5) * 5 AS Начало_периода,
    COUNT(*) AS Количество_дисциплин
FROM Дисциплины
WHERE Год_введения >= 1990
GROUP BY Начало_периода
ORDER BY Начало_периода;


