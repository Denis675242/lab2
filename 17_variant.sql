-- Запросы 3-6 изменяют данные/создают таблицу hourly_disciplines.
-- Выполняйте их по порядку в базе 17Var.

-- =========================================================
-- Задание 1. Выборка дисциплин, стандарт которых введён
-- более 5 лет назад.
-- EXTRACT извлекает текущий год из даты; CURRENT_DATE
-- возвращает текущую дату.
-- =========================================================
SELECT *
FROM disciplines
WHERE standard_year < EXTRACT(YEAR FROM CURRENT_DATE) - 5;


-- =========================================================
-- Задание 2. Выборка дисциплин, которые читают преподаватели
-- с почасовой оплатой. JOIN объединяет таблицы по ID дисциплины.
-- =========================================================
SELECT d.*
FROM disciplines d
JOIN workload w ON d.discipline_id = w.discipline_id
WHERE w.hourly_pay > 0;


-- =========================================================
-- Задание 3. Создание таблицы на основе выборки из задания 2.
-- DROP TABLE удаляет ранее созданную таблицу, если она есть,
-- чтобы скрипт можно было повторно запустить с начала.
-- =========================================================
DROP TABLE IF EXISTS hourly_disciplines;

CREATE TABLE hourly_disciplines AS
SELECT d.discipline_id,
       d.discipline_name,
       d.description,
       d.standard_year
FROM disciplines d
JOIN workload w ON d.discipline_id = w.discipline_id
WHERE w.hourly_pay > 0;


-- =========================================================
-- Задание 4. Добавление дисциплин, название которых начинается
-- с "Основы" и содержит дальнейшие слова.
-- NOT EXISTS не добавляет повторно уже имеющийся ID.
-- =========================================================
INSERT INTO hourly_disciplines
    (discipline_id, discipline_name, description, standard_year)
SELECT d.discipline_id,
       d.discipline_name,
       d.description,
       d.standard_year
FROM disciplines d
WHERE d.discipline_name LIKE 'Основы %'
  AND NOT EXISTS (
      SELECT 1
      FROM hourly_disciplines h
      WHERE h.discipline_id = d.discipline_id
  );


-- =========================================================
-- Задание 5. Изменение года введения на 2009 для дисциплин
-- с чётным ID. % — остаток от деления; 0 означает чётный ID.
-- =========================================================
UPDATE hourly_disciplines
SET standard_year = 2009
WHERE discipline_id % 2 = 0;


-- =========================================================
-- Задание 6. Удаление дисциплин, в названии которых
-- встречается слово "математика".
-- ILIKE выполняет поиск без учёта регистра.
-- =========================================================
DELETE FROM hourly_disciplines
WHERE discipline_name ILIKE '%математика%';


-- =========================================================
-- Задание 7. Групповой запрос: подсчёт дисциплин по 5-летним
-- периодам начиная с 1990 года.
-- COUNT — агрегатная функция, считает количество строк.
-- =========================================================
SELECT
    1990 + ((standard_year - 1990) / 5) * 5 AS period_start,
    COUNT(*) AS discipline_count
FROM disciplines
WHERE standard_year >= 1990
GROUP BY period_start
ORDER BY period_start;


